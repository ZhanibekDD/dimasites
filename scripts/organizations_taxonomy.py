GENERIC_NAME = re.compile(
    r"^(?:строительная компания|проектная организация|управляющая компания|компания по .+|фирма по .+|"
    r"магазин|склад|офис|котельная|очистные сооружения|жилой комплекс|строящийся жилой комплекс)$",
    re.IGNORECASE,
)

IRRELEVANT_NAME = re.compile(
    r"(?:\bавтомойк|\bавтосервис|\bавтотехцентр|\bавтоцентр|\bшиномонтаж|\bдетейлинг|"
    r"^\s*жк\b|жилой комплекс|новостройк|паспортн(?:ый|ого) стол|салон красоты|"
    r"парикмахер|ногтев|магазин электроники|магазин цифровой|бытовой техник|"
    r"ремонт телефонов|магазин мототехники|велосипед|автоэмал|\bфаркоп|"
    r"продуктовая компания|защита растений|агродрон|^\s*корма\s*$|\bсто кормов\b|"
    r"\bпункт выдачи\b|\bмагазин\b|\bгипермаркет\b|\bмаркетплейс\b|\bторговая сеть\b|"
    r"\bсалон (?:сантех|двер|окон|плит|интерьер|отделоч))",
    re.IGNORECASE,
)

COMPILED = {
    key: [re.compile(pattern, re.IGNORECASE) for pattern in item["patterns"]]
    for key, item in GROUPS.items()
}


def split_values(value: object) -> list[str]:
    if value is None:
        return []
    text = str(value).strip()
    if not text or text.casefold() == "nan":
        return []
    return [part.strip() for part in text.split(",") if part.strip()]


def classify(name: str, rubrics: list[str], subrubrics: list[str]) -> tuple[list[str], list[str]]:
    if GENERIC_NAME.fullmatch(name.strip()) or IRRELEVANT_NAME.search(name):
        return [], []

    matched_groups = []
    matched_subrubrics = []
    for group, patterns in COMPILED.items():
        matches = [item for item in subrubrics if any(pattern.search(item) for pattern in patterns)]
        if matches:
            matched_groups.append(group)
            matched_subrubrics.extend(matches)

    if "Автосервис" in set(rubrics):
        useful_for_heavy_equipment = {
            "Спецтехника", "Аренда спецтехники", "Запчасти для спецтехники", "Ремонт спецтехники",
        }
        if not useful_for_heavy_equipment.intersection(matched_subrubrics):
            return [], []

    return matched_groups, sorted(set(matched_subrubrics))
